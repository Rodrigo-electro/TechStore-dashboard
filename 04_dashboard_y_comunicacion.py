df_imp = pd.DataFrame({'feature': feature_names, 'importance': importances}).sort_values('importance', ascending=False)

print(f"✅ Total de características analizadas: {len(feature_names)}")

print("\n--- 5 Características más importantes ---")
print(df_imp.head(5))

print("\n--- 5 Características menos importantes ---")
print(df_imp.tail(5))

plt.figure(figsize=(10,6))
sns.barplot(data=df_imp.head(15), x='importance', y='feature', palette='viridis')
plt.title("Top 15 Factores que predicen la fuga de clientes")
plt.show()

# Guardar para el dashboard
df_imp.to_csv(f"{OUTPUT_DIR}/feature_importance_churn.csv", index=False)
print(f"✅ Importancia de características guardada en: {OUTPUT_DIR}/feature_importance_churn.csv")

"""## Preparación de datos para Forecast
No podemos hacer random split en series de tiempo, cortamos por fecha.
"""

# Forecast
# Usamos los últimos 6 meses como test
test_months = 6
train_data = df_ventas_ml.iloc[:-test_months]
