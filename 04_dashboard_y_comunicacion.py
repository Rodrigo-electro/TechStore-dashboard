plt.figure(figsize=(6,4))
sns.heatmap(confusion_matrix(y_test_c, preds_churn), annot=True, fmt='d', cmap='Blues')
plt.title("Matriz de Confusión - Predicción de Abandono")
plt.xlabel("Predicho")
plt.ylabel("Real")
plt.show()

