print("ANÁLISIS DE SESGO Y EQUIDAD EN LA PREDICCIÓN DE CHURN ")
print("\nPrecisión (Accuracy) por Segmento ")
for col in seg_cols:
    segment_name = col.replace('segmento_', '')
    subset = df_audit[df_audit[col] == 1]

    if len(subset) > 0:
        acc = subset[subset['churn_real'] == subset['churn_pred']].shape[0] / len(subset)
        print(f"Accuracy en segmento '{segment_name}': {acc:.2%}")
    else:
        print(f"No hay datos para el segmento '{segment_name}' en el conjunto de prueba.")

print("\nTasa de Falsos Positivos (FPR) por Segmento (Igualdad de Oportunidades) ")
print("¿Estamos etiquetando erróneamente como 'Riesgo' a un grupo más que a otro?")
for col in seg_cols:
    segment_name = col.replace('segmento_', '')
    subset = df_audit[df_audit[col] == 1]

    if len(subset) > 0:
        # Clientes que realmente NO abandonaron (churn_real == 0)
        non_churners = subset[subset['churn_real'] == 0]

        if len(non_churners) > 0:
            # Falsos Positivos: predijo 1 (churn), pero era 0 (no churn)
            false_positives = non_churners[non_churners['churn_pred'] == 1].shape[0]
            # Verdaderos Negativos: predijo 0 (no churn), y era 0 (no churn)
            true_negatives = non_churners[non_churners['churn_pred'] == 0].shape[0]

            fpr = false_positives / (false_positives + true_negatives)
            print(f"FPR en segmento '{segment_name}': {fpr:.2%}")
        else:
            print(f"No hay clientes 'No Churn' en el segmento '{segment_name}' para calcular FPR.")
    else:
        print(f"No hay datos para el segmento '{segment_name}' en el conjunto de prueba.")

print("\nAnálisis de sesgo completado.")

"""## Sistema de alertas automáticas 🚨"""

# Monitoreo y alertas
def trigger_alert(metric, threshold, message, is_higher_critical=False):
    if is_higher_critical:
        if metric > threshold:
            return f"🔴 CRITICAL: {message}"
    else:
        if metric < threshold:
            return f"🔴 CRITICAL: {message}"
    return f"🟢 OK: {message}"

# Umbrales definidos por negocio
# Para Accuracy, 'más alto es mejor', por lo que es crítico si está por debajo del umbral.
status_acc = trigger_alert(0.85, 0.80, "Accuracy del Modelo de Churn")

# Para MAE (Error Absoluto en Ventas), 'más bajo es mejor', por lo que es crítico si está por encima del umbral.
status_roi = trigger_alert(mae, 10000, "Error absoluto en Ventas (MAE)", is_higher_critical=True) # Si error > 10k, alerta

print(f"ESTADO DEL SISTEMA:\n{status_acc}\n{status_roi}")

